#!/usr/bin/env python3
"""Validate portable case contracts and their source projection, without HTTP."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import jsonschema
import yaml

from audit_lrs_source_projection import DEFAULT_SOURCE, ROOT, audit


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--skip-source", action="store_true")
    parser.add_argument("--definitions-only", action="store_true",
                        help="Compatibility flag: all modes check static definitions; expansion uses fixed signature inputs")
    parser.add_argument("--allow-review-pending", action="store_true",
                        help="Compatibility option; all modes validate correspondence without a review receipt")
    parser.add_argument("--verify-artifacts", action="store_true",
                        help="Verify all locked inputs/outputs already generated by the caller; do not expand twice")
    args = parser.parse_args()
    subprocess.run(
        [
            sys.executable,
            "-B",
            str(ROOT / "scripts/ci/lrs_generated_artifacts.py"),
            "verify" if args.verify_artifacts else "generate",
        ],
        check=True,
    )
    subprocess.run(
        [sys.executable, "-B", str(ROOT / "scripts/ci/generate_issued_test_projection.py"), "--check", "--require-complete"],
        check=True,
    )
    schema = json.loads(
        (ROOT / "spec/conformance/schemas/conformance-case.schema.json").read_text()
    )
    jsonschema.Draft202012Validator.check_schema(schema)
    validator = jsonschema.Draft202012Validator(schema)
    count = 0
    for path in sorted((ROOT / "tests/conformance/http").rglob("*.yaml")):
        data = yaml.load(
            path.read_text(), Loader=getattr(yaml, "CSafeLoader", yaml.SafeLoader)
        )
        errors = list(validator.iter_errors(data))
        if errors:
            raise SystemExit(
                f"{path.relative_to(ROOT)} {errors[0].json_path}: {errors[0].message}"
            )
        count += len(data["cases"])
    result = audit(None if args.skip_source else args.source, False)
    if result["cases_without_source_rule"]:
        raise SystemExit(f"unbound cases: {result['cases_without_source_rule']}")
    print(
        f"validated {count} portable cases; source bytes verified: {result['source_bytes_verified']}"
    )


if __name__ == "__main__":
    main()
