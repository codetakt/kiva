"""Real Git index controls for generated-output publication boundaries."""
import json
from pathlib import Path
import subprocess
import tempfile
import unittest

from check_generated_artifacts_index import INVENTORY, tracked_outputs


class GeneratedArtifactIndexTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='kiva-generated-index-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.git('init', '-q')
        self.output = 'generated/output.rs'
        (self.root/'generated').mkdir()
        (self.root/self.output).write_text('generated bytes\n')
        (self.root/'.gitignore').write_text('/generated/\n')
        path = self.root/INVENTORY
        path.parent.mkdir(parents=True)
        path.write_text(json.dumps({'stages': [{'outputs': [self.output]}]}))
        self.git('add', '.gitignore', INVENTORY)

    def git(self, *args):
        return subprocess.check_output(['git', *args], cwd=self.root, stderr=subprocess.STDOUT)

    def test_materialized_but_ignored_output_is_allowed(self):
        self.assertEqual(tracked_outputs(self.root), [])

    def test_forced_add_is_rejected_even_when_gitignored(self):
        self.git('add', '-f', self.output)
        self.assertEqual(tracked_outputs(self.root), [self.output])

    def test_removing_tracking_preserves_local_output(self):
        self.git('add', '-f', self.output)
        self.git('rm', '--cached', self.output)
        self.assertTrue((self.root/self.output).is_file())
        self.assertEqual(tracked_outputs(self.root), [])

    def test_unstaged_recipe_cannot_hide_a_staged_output(self):
        self.git('add', '-f', self.output)
        (self.root/INVENTORY).write_text(json.dumps({'stages': []}))
        self.assertEqual(tracked_outputs(self.root), [self.output])


if __name__ == '__main__':
    unittest.main()
