#!/usr/bin/env python3
"""Reproduce and identify static LRS artifacts without running the test suite.

The inventory is the classification/recipe; the lock records exact inputs and
outputs. A lock refresh records identity, never semantic approval.
Expansion runs in an empty temporary tree containing only declared inputs.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
INVENTORY = "spec/conformance/lrs-generated-artifacts.json"
LOCK = "spec/conformance/lrs-generated-artifacts.lock.json"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def safe_path(root, name):
    path = Path(name)
    require(not path.is_absolute() and ".." not in path.parts, f"unsafe path: {name}")
    target = root / path
    require(target.resolve().is_relative_to(root.resolve()), f"path escapes root: {name}")
    require(not target.is_symlink(), f"symlink is not an artifact/input: {name}")
    return target


def identity(path):
    data = path.read_bytes()
    return {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}


def write_json(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def toolchain():
    require(yaml.__with_libyaml__, "PyYAML with LibYAML is required")
    return {
        "python_implementation": platform.python_implementation(),
        "python": platform.python_version(),
        "pyyaml": yaml.__version__,
        "libyaml": yaml._yaml.get_version_string(),
    }


def inventory(root):
    spec = json.loads((root / INVENTORY).read_text())
    require(spec["schema_version"] == 1, "unsupported artifact inventory")
    outputs = [p for stage in spec["stages"] for p in stage["outputs"]]
    require(len(outputs) == len(set(outputs)), "duplicate output in inventory")
    require(LOCK not in outputs, "the lock cannot be generated by a producer")
    inputs = set(spec["inputs"])
    for pattern in spec["input_globs"]:
        require(not Path(pattern).is_absolute() and ".." not in Path(pattern).parts,
                f"unsafe input glob: {pattern}")
        matches = [p for p in root.glob(pattern) if p.is_file()]
        require(matches, f"input glob has no matches: {pattern}")
        inputs.update(str(p.relative_to(root)) for p in matches)
    inputs.difference_update(outputs)
    require(LOCK not in inputs, "the lock must not depend on itself")
    require(INVENTORY in inputs, "inventory must bind its own recipe")
    for name in inputs | set(outputs):
        safe_path(root, name)
    for stage in spec["stages"]:
        require(stage["script"] in inputs, f"producer not bound: {stage['script']}")
    unexpected = {str(p.relative_to(root)) for p in
                  (root / "tests/conformance/http/generated").rglob("*") if p.is_file()} - set(outputs)
    require(not unexpected, f"undeclared generated files: {sorted(unexpected)}")
    return spec, sorted(inputs), sorted(outputs)


def identities(root, paths):
    return {name: identity(safe_path(root, name)) for name in paths}


def verify_map(root, expected, label):
    for name, entry in expected.items():
        path = safe_path(root, name)
        require(path.is_file(), f"missing {label}: {name}; run lrs_generated_artifacts.py generate")
        require(identity(path) == entry, f"{label} drift: {name}")


def require_generated_cases(root):
    """Prevent the standard suite's consumers from silently loading a subset."""
    spec = json.loads((root / INVENTORY).read_text())
    names = [name for stage in spec["stages"] for name in stage["outputs"]
             if name.startswith("tests/conformance/http/")]
    require(names, "artifact inventory declares no generated cases")
    for name in names:
        require(safe_path(root, name).is_file(),
                f"missing generated cases: {name}; run lrs_generated_artifacts.py generate")


def verify_inputs(root, inputs, outputs):
    lock = json.loads((root / LOCK).read_text())
    require(lock["schema_version"] == 1, "unsupported artifact lock")
    require(set(lock["inputs"]) == set(inputs), "artifact input inventory drift")
    require(set(lock["outputs"]) == set(outputs), "artifact output inventory drift")
    require(lock["toolchain"] == toolchain(),
            f"generation toolchain drift: expected {lock['toolchain']}, got {toolchain()}")
    verify_map(root, lock["inputs"], "input")
    return lock


def expand(root, workspace, spec, inputs, outputs, seed):
    for name in inputs:
        target = workspace / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(safe_path(root, name), target)
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1", PYTHONHASHSEED=seed,
               PYTHONUTF8="1", TZ="UTC")
    for stage in spec["stages"]:
        print(f"static expansion: {stage['id']}", flush=True)
        subprocess.run([sys.executable, "-B", str(workspace / stage["script"]),
                        *stage["args"]], cwd=workspace, env=env, check=True)
    files = {str(p.relative_to(workspace)) for p in workspace.rglob("*") if p.is_file()}
    require(files == set(inputs) | set(outputs),
            f"undeclared/missing producer outputs: {sorted(files ^ (set(inputs) | set(outputs)))}")
    verify_map(workspace, identities(root, inputs), "producer input mutation")


def materialize(workspace, root, outputs):
    for name in outputs:
        path = safe_path(root, name)
        path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(workspace / name, path)


def bundle(root, lock, destination):
    verify_map(root, lock["outputs"], "output")
    destination.parent.mkdir(parents=True, exist_ok=True)
    names = sorted(set(lock["inputs"]) | set(lock["outputs"]) | {LOCK})
    require(destination.resolve() not in {(root / n).resolve() for n in names},
            "bundle would overwrite an input or output")
    # Normalize order, owner, modes, gzip name and all timestamps.
    with destination.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as compressed:
            with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as archive:
                for name in names:
                    path = root / name
                    info = tarfile.TarInfo(name)
                    info.size = path.stat().st_size
                    info.mode = 0o644
                    with path.open("rb") as stream:
                        archive.addfile(info, stream)
    print(json.dumps({"bundle": str(destination), **identity(destination),
                      "members": len(names)}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["generate", "check", "verify", "refresh", "bundle"])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path, help="bundle destination (required for bundle)")
    args = parser.parse_args()
    root = args.root.resolve()
    spec, inputs, outputs = inventory(root)
    lock = None if args.action == "refresh" else verify_inputs(root, inputs, outputs)
    if args.action == "bundle":
        require(args.output is not None, "bundle requires --output")
        bundle(root, lock, args.output)
    elif args.action == "verify":
        verify_map(root, lock["outputs"], "output")
        print(f"verified {len(inputs)} inputs and {len(outputs)} outputs; no semantic acceptance")
    else:
        with tempfile.TemporaryDirectory(prefix="kiva-lrs-static-") as temp:
            workspace = Path(temp)
            before = identities(root, inputs)
            expand(root, workspace, spec, inputs, outputs,
                   "1" if args.action == "check" else "0")
            verify_map(root, before, "input changed during generation")
            if args.action == "refresh":
                lock = {"schema_version": 1, "claim": "Reproducible static artifacts only; official review is the GitHub PR merge",
                        "toolchain": toolchain(), "inputs": before,
                        "outputs": identities(workspace, outputs)}
                materialize(workspace, root, outputs)
                write_json(root / LOCK, lock)
                print("refreshed artifact identities; no review approval is implied")
            else:
                verify_map(workspace, lock["outputs"], "reproduced output")
                if args.action == "generate":
                    materialize(workspace, root, outputs)
                else:
                    present = {n: v for n, v in lock["outputs"].items() if (root / n).exists()}
                    verify_map(root, present, "materialized output")
                print(f"reproduced {len(outputs)} locked artifacts from {len(inputs)} inputs")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, FileNotFoundError, subprocess.CalledProcessError) as error:
        raise SystemExit(str(error)) from error
