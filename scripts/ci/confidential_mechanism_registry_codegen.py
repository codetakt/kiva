"""Rust code generation for the confidential mechanism registry."""

from __future__ import annotations

from pathlib import Path
from typing import Any


def rust_bool(value: bool) -> str:
    """Render a Rust boolean literal."""
    return "true" if value else "false"


def render_registry(rows: list[dict[str, Any]], source_path: Path) -> str:
    """Render the generated Rust confidential mechanism registry."""
    lines = [
        "//! Confidential mechanism registry.",
        "//!",
        f"//! @generated by `scripts/ci/generate_confidential_mechanism_catalog.py` from `{source_path.as_posix()}`.",
        "//! Do not edit by hand.",
        "",
        "use super::workflow::{ConfidentialMechanismKind, Technique};",
        "use kiva_secret_provider_contract::SecretComputeProviderCapability;",
        "",
        "/// Stable descriptor for one confidential-computation mechanism boundary.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct ConfidentialMechanismDescriptor {",
        "    kind: ConfidentialMechanismKind,",
        "    technique: Technique,",
        "    required_provider_capability: SecretComputeProviderCapability,",
        "    production_provider_review_required: bool,",
        "    requires_all_participants: bool,",
        "}",
        "",
        "impl ConfidentialMechanismDescriptor {",
        "    /// Creates a mechanism descriptor.",
        "    #[must_use]",
        "    pub const fn new(kind: ConfidentialMechanismKind) -> Self {",
        "        descriptor_for_mechanism(kind)",
        "    }",
        "",
        "    /// Creates a descriptor row for the canonical mechanism registry.",
        "    #[must_use]",
        "    const fn from_parts(",
        "        kind: ConfidentialMechanismKind,",
        "        technique: Technique,",
        "        required_provider_capability: SecretComputeProviderCapability,",
        "        production_provider_review_required: bool,",
        "        requires_all_participants: bool,",
        "    ) -> Self {",
        "        Self {",
        "            kind,",
        "            technique,",
        "            required_provider_capability,",
        "            production_provider_review_required,",
        "            requires_all_participants,",
        "        }",
        "    }",
        "",
        "    /// Returns the concrete mechanism kind.",
        "    #[must_use]",
        "    pub const fn kind(self) -> ConfidentialMechanismKind {",
        "        self.kind",
        "    }",
        "",
        "    /// Returns the mechanism technique family.",
        "    #[must_use]",
        "    pub const fn technique(self) -> Technique {",
        "        self.technique",
        "    }",
        "",
        "    /// Returns the required provider capability for admitted provider bindings.",
        "    #[must_use]",
        "    pub const fn required_provider_capability(self) -> SecretComputeProviderCapability {",
        "        self.required_provider_capability",
        "    }",
        "",
        "    /// Returns whether production claims require externally reviewed provider evidence.",
        "    #[must_use]",
        "    pub const fn production_provider_review_required(self) -> bool {",
        "        self.production_provider_review_required",
        "    }",
        "",
        "    /// Returns whether the release policy must require all participants.",
        "    #[must_use]",
        "    pub const fn requires_all_participants(self) -> bool {",
        "        self.requires_all_participants",
        "    }",
        "}",
        "",
        "/// Stable registry of Kiva confidential mechanism descriptors.",
        f"pub const CONFIDENTIAL_MECHANISM_REGISTRY: [ConfidentialMechanismDescriptor; {len(rows)}] = [",
    ]
    for row in rows:
        lines.extend(
            [
                "    ConfidentialMechanismDescriptor::from_parts(",
                f"        {row['rust_kind']},",
                f"        {row['rust_technique']},",
                f"        {row['rust_required_provider_capability']},",
                f"        {rust_bool(row['production_provider_review_required'])},",
                f"        {rust_bool(row['requires_all_participants'])},",
                "    ),",
            ]
        )
    lines.extend(
        [
            "];",
            "",
            "/// Returns all registered confidential mechanism descriptors.",
            "#[must_use]",
            "pub const fn confidential_mechanism_registry() -> &'static [ConfidentialMechanismDescriptor] {",
            "    &CONFIDENTIAL_MECHANISM_REGISTRY",
            "}",
            "",
            "/// Returns the descriptor for a concrete mechanism kind.",
            "#[must_use]",
            "pub const fn descriptor_for_mechanism(",
            "    kind: ConfidentialMechanismKind,",
            ") -> ConfidentialMechanismDescriptor {",
            "    match kind {",
        ]
    )
    for index, row in enumerate(rows):
        single_line = f"        {row['rust_kind']} => CONFIDENTIAL_MECHANISM_REGISTRY[{index}],"
        if len(single_line) <= 100:
            lines.append(single_line)
        else:
            lines.extend(
                [
                    f"        {row['rust_kind']} => {{",
                    f"            CONFIDENTIAL_MECHANISM_REGISTRY[{index}]",
                    "        }",
                ]
            )
    lines.extend(
        [
            "    }",
            "}",
            "",
            "/// Returns whether a mechanism requires externally reviewed provider evidence for production.",
            "#[must_use]",
            "pub const fn mechanism_requires_production_provider_review(",
            "    kind: ConfidentialMechanismKind,",
            ") -> bool {",
            "    descriptor_for_mechanism(kind).production_provider_review_required()",
            "}",
            "",
            "#[cfg(test)]",
            "mod tests {",
            "    use super::*;",
            "",
            "    #[test]",
            "    fn registry_covers_all_current_mechanisms() {",
            "        for kind in [",
        ]
    )
    for row in rows:
        lines.append(f"            {row['rust_kind']},")
    lines.extend(
        [
            "        ] {",
            "            let descriptor = descriptor_for_mechanism(kind);",
            "            assert_eq!(descriptor.kind(), kind);",
            "            assert_eq!(ConfidentialMechanismDescriptor::new(kind), descriptor);",
            "        }",
            f"        assert_eq!(confidential_mechanism_registry().len(), {len(rows)});",
            "    }",
            "",
            "    #[test]",
            "    fn registry_marks_review_gated_external_runtime_boundaries() {",
        ]
    )
    for row in rows:
        assertion_prefix = "assert!(" if row["production_provider_review_required"] else "assert!(!"
        lines.extend(
            [
                f"        {assertion_prefix}mechanism_requires_production_provider_review(",
                f"            {row['rust_kind']}",
                "        ));",
            ]
        )
    lines.extend(
        [
            "    }",
            "",
            "    #[test]",
            "    fn mechanism_labels_round_trip() {",
            "        for descriptor in confidential_mechanism_registry() {",
            "            let kind = descriptor.kind();",
            "            assert_eq!(",
            "                ConfidentialMechanismKind::from_label(kind.label()),",
            "                Some(kind)",
            "            );",
            "        }",
            "        assert_eq!(ConfidentialMechanismKind::from_label(\"unknown\"), None);",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)
